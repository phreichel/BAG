//*****************************************************************************
package pr.x.nn.em;
//*****************************************************************************

import java.util.ArrayList;
import java.util.List;

//*****************************************************************************
public class Unit {

	//=========================================================================
	private static List<Unit> units = new ArrayList<Unit>();
	//=========================================================================

	//=========================================================================
	public static int count() {
		return units.size();
	}
	//=========================================================================

	//=========================================================================
	public static int count(int c) {
		c = c % units.size();
		c = c >= 0 ? c : units.size() - c;
		return c;
	}
	//=========================================================================

	//=========================================================================
	public static Unit create() {
		return new Unit();
	}
	//=========================================================================
	
	//=========================================================================
	public static Unit unit(int c) {
		c = count(c);
		return units.get(c);
	}
	//=========================================================================

	//=========================================================================
	private int number;
	private List<Rule> rules = new ArrayList<Rule>();
	//=========================================================================

	//=========================================================================
	private Unit() {
		number = units.size();
		units.add(this);
	}
	//=========================================================================
	
	//=========================================================================
	public int number() {
		return number;
	}
	//=========================================================================

	//=========================================================================
	public int rules() {
		return rules.size();
	}
	//=========================================================================

	//=========================================================================
	public Rule rule(int r) {
		return rules.get(r);
	}
	//=========================================================================

	//=========================================================================
	public void apply(Grid grid, int x, int y) {
		for (int i=0; i<rules(); i++) {
			boolean result = rule(i).apply(grid, x, y);
			if (result) break;
		}
	}
	//=========================================================================
	
}
//*****************************************************************************
