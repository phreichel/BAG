//*****************************************************************************
package pr.x.nn.em;
//*****************************************************************************

import java.util.Random;

//*****************************************************************************
public class Grid {

	//=========================================================================
	private int     width;
	private int     height;
	private int[][] prev;
	private int[][] next;
	private int[]   sequence;
	//=========================================================================

	//=========================================================================
	public Grid() {
		this(1000, 1000);
	}
	//=========================================================================

	//=========================================================================
	public Grid(int w, int h) {
		width  = w;
		height = h;
		prev = new int[width][height];
		next = new int[width][height];
		sequence = new int[width * height];
		for (int i=0; i< sequence.length; i++) {
			sequence[i] = i;
		}
		shuffle(sequence, System.currentTimeMillis());
	}
	//=========================================================================
	
	//=========================================================================
	private void shuffle(int[] a, long seed) {
		Random rng = new Random(seed);
	    for (int i = a.length - 1; i > 0; i--) {
	        int j = rng.nextInt(i + 1);
	        int tmp = a[i];
	        a[i] = a[j];
	        a[j] = tmp;
	    }
	}
	//=========================================================================
	
	//=========================================================================
	public int width() {
		return width;
	}
	//=========================================================================
	
	//=========================================================================
	public int height() {
		return height;
	}
	//=========================================================================

	//=========================================================================
	public Integer get(int w, int h) {
		w = width(w);
		h = height(h);
		return prev[w][h];
	}
	//=========================================================================

	//=========================================================================
	public void set(int w, int h, int v) {
		w = width(w);
		h = height(h);
		next[w][h] = v;
	}
	//=========================================================================

	//=========================================================================
	public int width(int w) {
		w = w % width;
		w = w >= 0 ? w : width  - w;
		return w;
	}
	//=========================================================================

	//=========================================================================
	public int height(int h) {
		h = h % height;
		h = h >= 0 ? h : height - h;
		return h;
	}
	//=========================================================================

	//=========================================================================
	public void apply() {
		for (int i=0; i<sequence.length; i++) {
			int v = sequence[i];
			int x = v % width;
			int y = v / width;
			apply(x, y);
		}
		for (int x=0; x<width; x++) {
			for (int y=0; y<height; y++) {
				prev[x][y] = next[x][y];
			}
		}
 	}
	//=========================================================================

	//=========================================================================
	public void apply(int x, int y) {
		int  value = prev[x][y];
		Unit unit  = Unit.unit(value);
		unit.apply(this, x, y);
	}
	//=========================================================================
	
}
//*****************************************************************************
