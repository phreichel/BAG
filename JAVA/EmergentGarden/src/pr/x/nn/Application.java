//*****************************************************************************
package pr.x.nn;
//*****************************************************************************

import pr.x.nn.ui.MainFrame;

//*****************************************************************************
public class Application {

	//=========================================================================
	private MainFrame frame;
	//=========================================================================
	
	//=========================================================================
	public Application() {
		super();
		frame = MainFrame.create();
	}
	//=========================================================================

	//=========================================================================
	public void run() {		
		while (frame.isVisible()) {
			Thread.yield();
		}
	}
	//=========================================================================
	
}
