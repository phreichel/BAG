//*****************************************************************************
package pr.x.nn.ui;

import java.util.ResourceBundle;

//*****************************************************************************

//*****************************************************************************
public class Asset {

	//=========================================================================
	private static ResourceBundle bundle = ResourceBundle.getBundle("asset");
	//=========================================================================
	
	//=========================================================================
	private Asset() {};
	//=========================================================================

	//=========================================================================
	public static final String msg(
			String name,
			Object ... args) {
		var msg = bundle.getString(name);
		if (args != null) {
			for (int i=0; i<args.length; i++) {
				var key = "${" + i + "}";
				var arg = args[i].toString();
				msg = msg.replace(key, arg);
			}
		}
		return msg;
	}
	//=========================================================================
	
}
//*****************************************************************************
