//*****************************************************************************
package homeapp.sv;
//*****************************************************************************

import homeapp.db.Node;

//*****************************************************************************
public class NodeDTA {

	//=========================================================================
	public Long id;
	public String label;
	public Integer quantity;
	public String serialNumber;
	//=========================================================================

	//=========================================================================
	public void set(Node node) {
		this.id = node.id;
		this.label = node.label;
		this.quantity = node.quantity;
		this.serialNumber = node.serialNumber;
	}
	//=========================================================================

	//=========================================================================
	public void get(Node node) {
		node.id = this.id;
		node.label = this.label;
		node.quantity = this.quantity;
		node.serialNumber = this.serialNumber;
	}
	//=========================================================================

}
//*****************************************************************************
