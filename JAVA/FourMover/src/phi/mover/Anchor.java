//*****************************************************************************
package phi.mover;
//*****************************************************************************

import javax.vecmath.Vector3f;

//*****************************************************************************
public class Anchor {

	//=========================================================================
	private Vector3f location = new Vector3f();
	private Joint    joint    = null;
	//=========================================================================
	
	//=========================================================================
	public Vector3f location() {
		return location;
	}
	//=========================================================================

	//=========================================================================
	public void location(Vector3f location) {
		this.location.set(location);
	}
	//=========================================================================

	//=========================================================================
	public Joint joint() {
		return joint;
	}
	//=========================================================================

	//=========================================================================
	public void joint(Joint joint) {
		this.joint = joint;
	}
	//=========================================================================
	
}
//*****************************************************************************
